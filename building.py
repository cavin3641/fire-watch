# -*- coding: utf-8 -*-
"""
건물 이름 뽑아내기

소방청 상세주소는 "565 선광아파트," 처럼 옵니다.
맨 앞 숫자는 번지이므로 **버리고**, 뒤의 건물 이름만 씁니다.

[중요] 번지는 저장하지도 표시하지도 않습니다.
       국민안전24가 화면에 읍·면·동까지만 보여주는 방침을 따릅니다.
       건물 이름만으로도 아파트인지 공장인지 구별이 됩니다.
"""
import re

# 건물 이름으로 종류를 추정합니다
BUILDING_RULES = [
    ("아파트", ["아파트", "APT", "에스에이치빌", "자이", "래미안", "푸르지오",
              "e편한", "이편한", "더샵", "힐스테이트", "롯데캐슬", "SK뷰",
              "센트레빌", "위브", "아이파크", "트리마제", "팰리스", "단지"]),
    ("공장·창고", ["공장", "산업", "제조", "물류", "창고", "공단", "테크노",
                "산단", "철강", "화학", "정비소", "작업장"]),
    ("상가·빌딩", ["상가", "빌딩", "프라자", "플라자", "타워", "센터", "몰",
                "시장", "마트", "백화점", "오피스", "스퀘어"]),
    ("숙박", ["모텔", "호텔", "여관", "펜션", "리조트", "게스트"]),
    ("요양·병원", ["요양", "병원", "의원", "재활", "복지관"]),
    ("교육·종교", ["어린이집", "유치원", "학교", "대학", "학원",
                "교회", "성당", "사찰", "관공서", "주민센터"]),
    ("주택·빌라", ["빌라", "연립", "다세대", "주택", "하우스", "맨션",
                "원룸", "고시원", "빌"]),
]

# 이런 값은 건물 이름이 아닙니다
NOISE = ["인근건물 정보", "방향", "쪽", "에서", "m ", "[↘]", "[↙]", "[↖]", "[↗]"]


def building_name(detail):
    """상세주소에서 건물 이름만 뽑습니다. 번지는 버립니다.

    "565 선광아파트,"        -> "선광아파트"
    "708 공릉아파트, 105동"  -> "공릉아파트"
    "697-54"                -> None  (번지뿐이면 없음)
    """
    if not detail:
        return None

    t = str(detail).strip()

    # '인근건물 정보: ...' 같은 안내문은 버립니다
    for bad in NOISE:
        if bad in t:
            return None

    # 맨 앞의 번지(숫자, 숫자-숫자)를 잘라냅니다
    t = re.sub(r"^\s*\d+(-\d+)*\s*", "", t)

    # 괄호, 쉼표 정리
    t = t.strip(" ,()[]")

    # 쉼표 앞까지만 (뒤는 보통 '105동' 같은 동 번호)
    if "," in t:
        t = t.split(",")[0].strip()

    # 이름 뒤에 붙은 동·호·층 번호를 떼어냅니다
    # "성복역금호베스트빌아파트 511동" -> "성복역금호베스트빌아파트"
    t = re.sub(r"[\s]*\d+(-\d+)*\s*(동|호|층)?\s*$", "", t).strip()

    # 남은 게 숫자뿐이거나 너무 짧으면 버립니다
    if not t or len(t) < 2:
        return None
    if re.fullmatch(r"[\d\s\-호동층]+", t):
        return None

    return t[:30]


def building_kind(name):
    """건물 이름으로 종류를 추정합니다. 모르면 None."""
    if not name:
        return None
    for kind, keywords in BUILDING_RULES:
        for kw in keywords:
            if kw in name:
                return kind
    return None


def enrich(row):
    """소방청 한 건에서 건물 이름과 종류를 뽑아 돌려줍니다."""
    name = building_name(row.get("dstrAreaDtl"))
    return name, building_kind(name)
